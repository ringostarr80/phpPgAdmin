import { existsSync, readFileSync, rmSync } from 'node:fs';
import { resolve } from 'node:path';

// Mirrors TestEnvironment::tearDown() in Tests/Support/TestEnvironment.php. It is done here instead of
// spawning `php`, so no command has to be looked up via PATH. The setup runs as part of the web server
// command in playwright.config.ts, because Playwright starts the web server before globalSetup.

/** Must match TestEnvironment::GENERATED_MARKER. */
const GENERATED_MARKER = '// Generated by Tests\\Support\\TestEnvironment, removed after the test run.';

export default function globalTeardown(): void {
  rmSync(resolve('conf', 'config-test.yml'), { force: true });

  // Only remove a config.inc.php the setup generated, never a developer's own.
  const configIncPhp = resolve('conf', 'config.inc.php');
  if (existsSync(configIncPhp) && readFileSync(configIncPhp, 'utf8').includes(GENERATED_MARKER)) {
    rmSync(configIncPhp);
  }
}
