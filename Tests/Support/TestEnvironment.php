<?php

declare(strict_types=1);

namespace Tests\Support;

use Dotenv\Dotenv;
use Symfony\Component\Yaml\Yaml;

/**
 * Writes the configuration the test suites run against and removes it again afterwards.
 *
 * Framework-independent on purpose: the Playwright E2E tests call it through `Tests/test-environment.php`,
 * the PHPUnit bootstrap can call it directly.
 */
final class TestEnvironment
{
    public const CONFIG_YAML_FILE = 'config-test.yml';

    public const NOT_RUNNING_SERVER_DESC = 'Not Running Server';
    public const NOT_RUNNING_SERVER_HOST = '127.0.0.1';

    /**
     * Nothing listens on port 1, so a login attempt is refused immediately
     * instead of waiting for a TCP timeout against an unreachable host.
     */
    public const NOT_RUNNING_SERVER_PORT = 1;

    public const RUNNING_SERVER_DESC = 'Running Server';
    public const RUNNING_SERVER_DEFAULT_HOST = '127.0.0.1';
    public const RUNNING_SERVER_PORT = 5_432;

    /**
     * Written into a generated config.inc.php, so tearDown() never deletes a config.inc.php it did not create.
     */
    private const GENERATED_MARKER = '// Generated by Tests\Support\TestEnvironment, removed after the test run.';

    public static function setUp(): void
    {
        Dotenv::createImmutable(self::rootDir())->safeLoad();

        $runningServerHost = self::getEnvVar('PHPPGADMIN_TEST_SERVER_HOSTNAME') ?? self::RUNNING_SERVER_DEFAULT_HOST;

        self::writeConfigYaml($runningServerHost);
        self::writeConfigIncPhp($runningServerHost);

        putenv('PHPPGADMIN_CONFIG_YAML_FILE=' . self::CONFIG_YAML_FILE);
    }

    public static function tearDown(): void
    {
        $configYaml = self::confDir() . DIRECTORY_SEPARATOR . self::CONFIG_YAML_FILE;

        if (file_exists($configYaml)) {
            unlink($configYaml);
        }

        $configIncPhp = self::confDir() . DIRECTORY_SEPARATOR . 'config.inc.php';

        if (
            file_exists($configIncPhp)
            && str_contains((string)file_get_contents($configIncPhp), self::GENERATED_MARKER)
        ) {
            unlink($configIncPhp);
        }
    }

    public static function getEnvVar(string $envName): ?string
    {
        if (isset($_ENV[$envName]) && is_string($_ENV[$envName])) {
            return $_ENV[$envName];
        }

        $envValue = getenv($envName);

        return is_string($envValue)
            ? $envValue
            : null;
    }

    private static function writeConfigYaml(string $runningServerHost): void
    {
        $config = [
            'servers' => [
                [
                    'desc' => self::NOT_RUNNING_SERVER_DESC,
                    'host' => self::NOT_RUNNING_SERVER_HOST,
                    'port' => self::NOT_RUNNING_SERVER_PORT,
                ],
                [
                    'desc' => self::RUNNING_SERVER_DESC,
                    'host' => $runningServerHost,
                    'port' => self::RUNNING_SERVER_PORT,
                ],
            ],
        ];

        $configYaml = self::confDir() . DIRECTORY_SEPARATOR . self::CONFIG_YAML_FILE;

        if (file_put_contents($configYaml, Yaml::dump($config)) === false) {
            throw new \RuntimeException("Failed to write {$configYaml}");
        }
    }

    /**
     * The legacy pages still read conf/config.inc.php. An existing one (e.g. a developer's own) is left untouched.
     */
    private static function writeConfigIncPhp(string $runningServerHost): void
    {
        $configIncPhp = self::confDir() . DIRECTORY_SEPARATOR . 'config.inc.php';

        if (file_exists($configIncPhp)) {
            return;
        }

        $content = file_get_contents($configIncPhp . '-dist');

        if ($content === false) {
            throw new \RuntimeException("Failed to read {$configIncPhp}-dist");
        }

        $content = str_replace(
            [
                "\$conf['servers'][0]['desc'] = 'PostgreSQL';",
                "\$conf['servers'][0]['host'] = '';",
                "\$conf['extra_login_security'] = true;",
            ],
            [
                "\$conf['servers'][0]['desc'] = '" . self::RUNNING_SERVER_DESC . "';",
                "\$conf['servers'][0]['host'] = '" . $runningServerHost . "';",
                "\$conf['extra_login_security'] = false;",
            ],
            $content,
        );
        $content = preg_replace('/^<\?php/', "<?php\n" . self::GENERATED_MARKER, $content, 1) ??
            throw new \RuntimeException("Failed to mark {$configIncPhp} as generated");

        if (file_put_contents($configIncPhp, $content) === false) {
            throw new \RuntimeException("Failed to write {$configIncPhp}");
        }
    }

    private static function confDir(): string
    {
        return self::rootDir() . DIRECTORY_SEPARATOR . 'conf';
    }

    private static function rootDir(): string
    {
        return dirname(__DIR__, 2);
    }
}
